#!/usr/bin/env bash
# Generate per-library unsafe-boundary maps for the Phase 2 release review.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/lang/docs/safety-sharpen/unsafe"
mkdir -p "$OUT"
LIBS=(std core fs path process environment net http tls encoding crypto compression archive image audio font regex json mime datetime uuid osrand cbor window webview page components router server)
for lib in "${LIBS[@]}"; do
  dir="$ROOT/lang/libs/$lib"
  [ -d "$dir" ] || continue
  paths=("$dir/src"); [ -d "$dir/posix" ] && paths+=("$dir/posix"); [ -d "$dir/win" ] && paths+=("$dir/win")
  {
    echo "# Unsafe boundary map: $lib"
    echo
    echo "Generated by scripts/safety-unsafe-map.sh. Every entry is a raw/FFI"
    echo "boundary; safe callers use the facade documented in the library README/api snapshot."
    echo
    echo "## Unsafe declarations"
    echo
    echo '```'
    rg --no-heading --line-number 'unsafe (func|impl|interface)' "${paths[@]}" 2>/dev/null | sed "s#^$ROOT/##" || true
    echo '```'
    echo
    echo "## Unsafe call/dereference sites (count)"
    echo
    printf -- '- unsafe blocks: %s\n' "$({ rg --no-heading 'unsafe\s*\{' "${paths[@]}" 2>/dev/null || true; } | wc -l)"
    printf -- '- unsafe expressions: %s\n' "$({ rg --no-heading 'unsafe\(' "${paths[@]}" 2>/dev/null || true; } | wc -l)"
    printf -- '- raw-pointer dereferences/indexing: %s\n' "$({ rg --no-heading '\[[^]]*\]|\*\w+' "${paths[@]}" 2>/dev/null || true; } | wc -l)"
    echo
    echo "Review rule: a safe wrapper must validate null/length/ownership before any raw call."
  } > "$OUT/$lib.md"
done
echo "Unsafe maps written to $OUT"
