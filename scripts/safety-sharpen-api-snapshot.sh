#!/usr/bin/env bash
# Generate public API snapshots for the Tier A safe libraries.
# The snapshot is deliberately textual: a reviewable diff is the gate.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
if ! command -v rg >/dev/null 2>&1; then
    echo "error: ripgrep (rg) is required to generate API snapshots" >&2
    exit 2
fi
OUT="$ROOT/lang/docs/safety-sharpen/api"
mkdir -p "$OUT"

LIBS=(std core fs path process environment net http tls encoding crypto compression archive image audio font regex json mime datetime uuid osrand cbor window webview page components router server)

for lib in "${LIBS[@]}"; do
    dir="$ROOT/lang/libs/$lib"
    [ -d "$dir" ] || continue
    {
        echo "# Public API snapshot: $lib"
        echo "# Generated by scripts/safety-sharpen-api-snapshot.sh; review diffs."
        echo
        paths=("$dir/src")
        [ -d "$dir/posix" ] && paths+=("$dir/posix")
        [ -d "$dir/win" ] && paths+=("$dir/win")
        rg --no-heading --line-number \
            '^[[:space:]]*(public[[:space:]]+)?(unsafe[[:space:]]+)?(public[[:space:]]+)?(func|struct|variant|interface|type)[[:space:]]' \
            "${paths[@]}" 2>/dev/null \
            | sed "s#^$ROOT/##" \
            | sort || true
    } > "$OUT/$lib.txt"
done

echo "API snapshots written to $OUT"
